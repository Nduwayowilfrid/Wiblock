/**
 * Generates a real, standardized XML GPX 1.1 file
 * Compatible with Xcode Location Simulation, 3uTools, Android Studio, and GPS JoyStick
 */
export function generateRealGpxFile(
  trackName: string,
  points: { lat: number; lng: number; time?: string }[]
): Blob {
  const now = new Date().toISOString();
  
  let gpxXml = `<?xml version="1.0" encoding="UTF-8" standalone="no" ?>
<gpx xmlns="http://www.topografix.com/GPX/1/1" creator="Wondershare Dr.Fone Virtual Location" version="1.1" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.topografix.com/GPX/1/1 http://www.topografix.com/GPX/1/1/gpx.xsd">
  <metadata>
    <name>${escapeXml(trackName)}</name>
    <desc>Generated by Dr.Fone Virtual Location Real GPS Engine</desc>
    <time>${now}</time>
  </metadata>
  <trk>
    <name>${escapeXml(trackName)}</name>
    <trkseg>
`;

  points.forEach((pt, idx) => {
    const ptTime = pt.time || new Date(Date.now() + idx * 2000).toISOString();
    gpxXml += `      <trkpt lat="${pt.lat.toFixed(6)}" lon="${pt.lng.toFixed(6)}">
        <ele>45.0</ele>
        <time>${ptTime}</time>
      </trkpt>\n`;
  });

  gpxXml += `    </trkseg>
  </trk>
</gpx>`;

  return new Blob([gpxXml], { type: 'application/gpx+xml' });
}

function escapeXml(unsafe: string): string {
  return unsafe.replace(/[<>&'"]/g, (c) => {
    switch (c) {
      case '<': return '&lt;';
      case '>': return '&gt;';
      case '&': return '&amp;';
      case '\'': return '&apos;';
      case '"': return '&quot;';
      default: return c;
    }
  });
}
